			const uint16_t* byName(const std::string& name)
			{
				if (name == "cp1251" || name == "windows-1251") return CP1251;
				if (name == "cp866" || name == "ibm866") return CP866;
				if (name == "cp437") return CP437;
				return nullptr;
			}

			void appendUtf8(std::string& out, uint32_t cp)
			{
				if (cp < 0x80) out += (char)cp;
				else if (cp < 0x800) { out += (char)(0xc0 | (cp >> 6)); out += (char)(0x80 | (cp & 0x3f)); }
				else if (cp < 0x10000) { out += (char)(0xe0 | (cp >> 12)); out += (char)(0x80 | ((cp >> 6) & 0x3f)); out += (char)(0x80 | (cp & 0x3f)); }
				else
				{
					out += (char)(0xf0 | (cp >> 18)); out += (char)(0x80 | ((cp >> 12) & 0x3f));
					out += (char)(0x80 | ((cp >> 6) & 0x3f)); out += (char)(0x80 | (cp & 0x3f));
				}
			}

			std::string toUtf8(const std::string& bytes, const uint16_t* table)
			{
				if (!table) return bytes;
				std::string out;
				for (unsigned char c : bytes)
				{
					if (c < 0x80) out += (char)c;
					else appendUtf8(out, table[c - 0x80]);
				}
				return out;
			}

			// the next code point of a UTF-8 string at i (advanced past it); a byte that isn't UTF-8 comes back as itself
			static uint32_t next(const std::string& s, size_t& i)
			{
				unsigned char c = (unsigned char)s[i++];
				int n = c >= 0xf0 ? 3 : c >= 0xe0 ? 2 : c >= 0xc0 ? 1 : 0;
				uint32_t cp = n == 3 ? c & 0x07 : n == 2 ? c & 0x0f : n == 1 ? c & 0x1f : c;
				for (int k = 0; k < n; k++)
				{
					if (i >= s.size() || ((unsigned char)s[i] & 0xc0) != 0x80) return c;
					cp = (cp << 6) | ((unsigned char)s[i++] & 0x3f);
				}
				return cp;
			}

			std::string fromUtf8(const std::string& utf8, const uint16_t* table)
			{
				if (!table) return utf8;
				std::string out;
				for (size_t i = 0; i < utf8.size();)
				{
					uint32_t cp = next(utf8, i);
					if (cp < 0x80) { out += (char)cp; continue; }
					char b = '?';
					for (int k = 0; k < 128; k++) if (table[k] == cp) { b = (char)(0x80 + k); break; }
					out += b;
				}
				return out;
			}

			bool validUtf8(const std::string& s)
			{
				for (size_t i = 0; i < s.size();)
				{
					unsigned char c = (unsigned char)s[i];
					int n = c < 0x80 ? 0 : (c & 0xe0) == 0xc0 ? 1 : (c & 0xf0) == 0xe0 ? 2 : (c & 0xf8) == 0xf0 ? 3 : -1;
					if (n < 0 || (n == 1 && c < 0xc2)) return false;
					for (int k = 1; k <= n; k++) if (i + k >= s.size() || ((unsigned char)s[i + k] & 0xc0) != 0x80) return false;
					i += n + 1;
				}
				return true;
			}
