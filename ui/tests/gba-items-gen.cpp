// Makes src/gba/gen3items.inc: the Gen III item ids (Ruby/Sapphire/Emerald/FireRed/LeafGreen share one numbering) in
// the DS games' (Gen IV's) item numbering, which the DS companion's model and logic use, by matching the item names
// of the player's own GBA and DS ROMs (no names are written out: only the numbers).
//   make tests/gba-items-gen && tests/gba-items-gen <Emerald.gba> <FireRed.gba> <HeartGold.nds> > src/gba/gen3items.inc
//   [src/gba/gen4names.inc]
// The optional fourth file: the Gen IV items told by their names for a ROM hack's own item table (gen3rom.cpp:
// itemByName) - each as a 32-bit hash of its name (FNV-1a of norm() below, so no names are written out) with its Gen IV
// id and DS pocket, from HeartGold's names and the GBA games' own spellings of the same items.
#include "nds/rom.h"
#include "pokemon.h"
#include <cctype>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <map>
#include <string>
#include <vector>

using namespace banana;

static std::vector<uint8_t> readFile(const char* p)
{
	std::ifstream f(p, std::ios::binary);
	return std::vector<uint8_t>((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
}

// a name to compare: letters and digits only, lower case, é as e ("POKé BALL" = "Poké Ball", "KINGS ROCK" = "King's Rock")
static std::string norm(const std::string& s)
{
	std::string o;
	for (size_t i = 0; i < s.size(); i++)
	{
		unsigned char c = (unsigned char)s[i];
		if (c == 0xc3 && i + 1 < s.size() && ((unsigned char)s[i + 1] == 0xa9 || (unsigned char)s[i + 1] == 0x89)) { o += 'e'; i++; continue; }
		if (isalnum(c)) o += (char)tolower(c);
	}
	return o;
}

int main(int argc, char** argv)
{
	if (argc < 4) { fprintf(stderr, "usage: %s <Emerald.gba> <FireRed.gba> <HeartGold.nds>\n", argv[0]); return 2; }
	std::vector<pkmn::RomTables::Item> g3;
	for (int i = 1; i <= 2; i++)
	{
		auto rom = readFile(argv[i]);
		auto t = pkmn::findTables(rom.data(), rom.size());
		if (t.items.empty()) { fprintf(stderr, "no items in %s\n", argv[i]); return 1; }
		if (g3.size() < t.items.size()) g3.resize(t.items.size());
		for (size_t k = 0; k < t.items.size(); k++)
			if (g3[k].name.empty() || g3[k].name.find('?') != std::string::npos) g3[k] = t.items[k];
	}
	std::string err;
	auto ds = nds::loadRom(argv[3], "", &err);
	if (!ds) { fprintf(stderr, "%s: %s\n", argv[3], err.c_str()); return 1; }
	std::map<std::string, uint16_t> byName;
	for (size_t k = 1; k < ds->items.size(); k++)
	{
		std::string n = norm(ds->items[k].name);
		if (!n.empty() && !byName.count(n)) byName[n] = (uint16_t)k;
	}
	// Gen III's own pockets as the DS companion's (1 Items, 2 Poké Balls, 3 TMs & HMs, 4 Berries, 5 Key Items)
	auto pocketOf = [](uint8_t p) -> int {
		switch (p) { case 2: return nds::POCKET_BALLS; case 3: return nds::POCKET_TMS; case 4: return nds::POCKET_BERRIES;
			case 5: return nds::POCKET_KEY; default: return nds::POCKET_ITEMS; }
	};
	printf("// generated by tests/gba-items-gen.cpp from the player's own ROMs (Emerald, FireRed, HeartGold): by Gen III item id,\n");
	printf("// { its Gen IV id (0: none, Gen III only), its DS pocket (model.h nds::Pocket) }\n");
	int matched = 0, only = 0;
	std::map<uint16_t, int> used;
	for (size_t k = 0; k < g3.size(); k++)
	{
		uint16_t g4 = 0;
		int pocket = pocketOf(g3[k].pocket);
		if (k >= 289 && k <= 338) g4 = (uint16_t)(328 + k - 289);			// TM01..TM50
		else if (k >= 339 && k <= 346) g4 = (uint16_t)(420 + k - 339);		// HM01..HM08
		else if (k)
		{
			auto it = byName.find(norm(g3[k].name));
			if (it != byName.end() && g3[k].name.find('?') == std::string::npos) g4 = it->second;
		}
		if (g4 && used.count(g4)) { fprintf(stderr, "%zu %s: %u already %d\n", k, g3[k].name.c_str(), g4, used[g4]); g4 = 0; }
		if (g4)
		{
			used[g4] = (int)k; matched++;
			// the Items pocket split as the DS games split it (medicine, battle items); Gen III's other pockets kept
			const int p4 = ds->items[g4].pocket;
			if (pocket == nds::POCKET_ITEMS && (p4 == nds::POCKET_MEDICINE || p4 == nds::POCKET_BATTLE || p4 == nds::POCKET_MAIL)) pocket = p4;
		}
		else if (k)
		{
			only++;
			if (k >= 121 && k <= 132) pocket = nds::POCKET_MAIL;
			fprintf(stderr, "Gen III only: %zu %s\n", k, g3[k].name.c_str());
		}
		printf("{ %u, %d },%s", g4, pocket, k % 8 == 7 ? "\n" : " ");
	}
	printf("\n");
	fprintf(stderr, "%zu items: %d matched, %d Gen III only\n", g3.size(), matched, only);
	if (argc > 4)
	{
		FILE* o = fopen(argv[4], "w");
		if (!o) { perror(argv[4]); return 1; }
		auto fnv = [](const std::string& s) { uint32_t h = 2166136261u; for (unsigned char c : s) { h ^= c; h *= 16777619u; } return h; };
		std::map<uint32_t, std::pair<uint16_t, int>> byHash;
		auto add = [&](const std::string& nm, uint16_t g4)
		{
			std::string k = norm(nm);
			if (k.empty() || !g4 || g4 >= ds->items.size()) return;
			uint32_t h = fnv(k);
			if (byHash.count(h) && byHash[h].first != g4) { fprintf(stderr, "hash clash: %s\n", nm.c_str()); return; }
			byHash[h] = { g4, ds->items[g4].pocket };
		};
		for (size_t k = 1; k < ds->items.size(); k++)
			if (ds->items[k].name.find('?') == std::string::npos) add(ds->items[k].name, (uint16_t)k);
		// (the GBA games' spellings: "X DEFEND", "PARLYZ HEAL" ...; TMs/HMs as above)
		for (size_t k = 1; k < g3.size(); k++)
		{
			uint16_t g4 = k >= 289 && k <= 338 ? (uint16_t)(328 + k - 289) : k >= 339 && k <= 346 ? (uint16_t)(420 + k - 339) : 0;
			if (!g4) { auto it = byName.find(norm(g3[k].name)); if (it != byName.end()) g4 = it->second; }
			if (g4 && g3[k].name.find('?') == std::string::npos) add(g3[k].name, g4);
		}
		fprintf(o, "// generated by tests/gba-items-gen.cpp from the player's own ROMs (Emerald, FireRed, HeartGold): the Gen IV items\n");
		fprintf(o, "// by a hash of their names (FNV-1a of the letters and digits in lower case, e for é), sorted: { hash, Gen IV id, DS pocket }\n");
		int c = 0;
		for (auto& e : byHash) fprintf(o, "{ 0x%08xu, %u, %d },%s", e.first, e.second.first, e.second.second, ++c % 4 == 0 ? "\n" : " ");
		fprintf(o, "\n");
		fclose(o);
		fprintf(stderr, "%d names hashed\n", c);
	}
	return 0;
}
