// Makes src/gba/expitems.inc: the DS games' (Gen IV's) item ids by a hash of the item's name, for the GBA ROM hacks
// built from pokeemerald-expansion (src/gba/expansion.cpp), whose item ids are their own: the player's own Emerald's
// names with Gen III's ids in Gen IV's numbering (gen3items.inc), and the Gen IV items the DS companion's logic knows
// by number (logic.cpp's I_ ids: balls, Plates, held items). No names are written out: a hash and the number only.
//   make tests/gba-expitems-gen && tests/gba-expitems-gen <Emerald.gba> > src/gba/expitems.inc
#include "gba/gen3rom.h"
#include "pokemon.h"
#include <cctype>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <map>

using namespace banana;

static std::string norm(const std::string& s)
{
	std::string o;
	for (size_t i = 0; i < s.size(); i++)
	{
		unsigned char c = (unsigned char)s[i];
		if (c == 0xc3 && i + 1 < s.size() && ((unsigned char)s[i + 1] == 0xa9 || (unsigned char)s[i + 1] == 0x89)) { o += 'e'; i++; continue; }
		if (isalnum(c)) o += (char)tolower(c);
	}
	return o;
}
static uint32_t fnv(const std::string& s) { uint32_t h = 2166136261u; for (unsigned char c : s) { h ^= c; h *= 16777619u; } return h; }

int main(int argc, char** argv)
{
	if (argc < 2) { fprintf(stderr, "usage: %s <Emerald.gba>\n", argv[0]); return 2; }
	std::ifstream f(argv[1], std::ios::binary);
	std::vector<uint8_t> b((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
	pkmn::RomTables t = pkmn::findTables(b.data(), b.size(), pkmn::detectGame(b.data(), b.size()));
	if (t.items.size() < 300) { fprintf(stderr, "no items in %s\n", argv[1]); return 1; }
	std::map<uint32_t, uint16_t> out;
	for (size_t i = 1; i < t.items.size(); i++)
	{
		uint16_t g = gba::itemToGen4((uint16_t)i);
		std::string k = norm(t.items[i].name);
		if (g && g < gba::GEN3_ONLY && !k.empty() && k.compare(0, 2, "tm") && k.compare(0, 2, "hm")) out.emplace(fnv(k), g);
	}
	static const struct { const char* name; uint16_t id; } GEN4[] = {
		{ "Dusk Ball", 13 }, { "Heal Ball", 14 }, { "Quick Ball", 15 }, { "Cherish Ball", 16 }, { "Muscle Band", 266 },
		{ "Wise Glasses", 267 }, { "Expert Belt", 268 }, { "Life Orb", 270 }, { "Choice Scarf", 287 }, { "Choice Specs", 297 },
		{ "Flame Plate", 298 }, { "Splash Plate", 299 }, { "Zap Plate", 300 }, { "Meadow Plate", 301 }, { "Icicle Plate", 302 },
		{ "Fist Plate", 303 }, { "Toxic Plate", 304 }, { "Earth Plate", 305 }, { "Sky Plate", 306 }, { "Mind Plate", 307 },
		{ "Insect Plate", 308 }, { "Stone Plate", 309 }, { "Spooky Plate", 310 }, { "Draco Plate", 311 }, { "Dread Plate", 312 },
		{ "Iron Plate", 313 }, { "Fast Ball", 492 }, { "Level Ball", 493 }, { "Lure Ball", 494 }, { "Heavy Ball", 495 },
		{ "Love Ball", 496 }, { "Friend Ball", 497 }, { "Moon Ball", 498 }, { "Sport Ball", 499 }, { "Park Ball", 500 },
		{ "Dream Ball", 576 } };
	for (auto& e : GEN4) out[fnv(norm(e.name))] = e.id;
	printf("// generated by tests/gba-expitems-gen.cpp from the player's own Emerald (and logic.cpp's Gen IV ids): { a hash of\n"
		"// the item's name (FNV-1a of its letters and digits, lower case), its Gen IV id }\n");
	int k = 0;
	for (auto& e : out) printf("{ 0x%08xu, %u },%s", e.first, e.second, ++k % 6 ? " " : "\n");
	printf("\n");
}
