import re
def cls(t):
    m = t.split()[0] if t else ''
    if 'x26' in t and ('[' in t): return 'fast memory access'
    if re.search(r'\[x29, #(3[6-9]|[4-8]\d|9[0-2])\]', t) and m.startswith('ldr'): return 'guest reg load'
    if re.search(r'\[x29, #(3[6-9]|[4-8]\d|9[0-2])\]', t) and m.startswith('str'): return 'guest reg store'
    if re.search(r'\[x29, #96\]', t): return 'R15 store'
    if re.search(r'\[x29, #100\]', t): return 'CPSR load/store'
    if '[x29' in t: return 'other CPU state ld/st'
    if m in ('mrs', 'msr') or 'w27' in t or m in ('cset', 'csetm'): return 'flags/CPSR'
    if 'w28' in t: return 'cycles'
    if m == 'bl': return 'bl (exit stub/call)'
    if m in ('b',) : return 'b (slot/jump)'
    if m.startswith('b.') or m in ('cbz', 'cbnz', 'tbz', 'tbnz'): return 'cond branch'
    if m in ('blr', 'br', 'ret'): return 'indirect'
    if m == '.inst' or m.startswith('udf') or m == '.word': return 'data (literal)'
    if m in ('mov', 'movz', 'movk', 'movn', 'adrp', 'adr') : return 'constants (mov/movk/adrp)'
    if m.startswith('ld') or m.startswith('st'): return 'other ld/st'
    return 'alu'
