#!/usr/bin/env python3
"""Bake the menu's banana (from ui/assets/rnds/logo@1x.png) into activity-logo.h.

The brand plate uses the same banana as the menu's own logo: the logo file is the banana
followed by the "BANANADS" wordmark, so this crops the banana (everything before the first
wide gap) and emits it as ARGB pixels, at 1x and at the Plus's 1.6x, like the font atlas.

    python tools/make-logo.py
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(APP, "..", "..", ".."))
ASSETS = os.path.join(ROOT, "ui", "assets", "rnds")


def banana_columns(im):
    """the columns of the banana: from its first inked column to the gap before the wordmark"""
    w, h = im.size
    cols = [any(im.getpixel((x, y))[3] > 8 for y in range(h)) for x in range(w)]
    start = next(i for i, c in enumerate(cols) if c)
    gap = 0
    for x in range(start, w):
        if cols[x]:
            gap = 0
        else:
            gap += 1
            if gap >= 3:
                return start, x - gap + 1
    return start, w


def emit(f, name, im):
    w, h = im.size
    f.write(f"static const uint32_t {name}_PX[] = {{\n")
    for y in range(h):
        row = []
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            row.append(f"0x{a:02x}{r:02x}{g:02x}{b:02x}")
        f.write(",".join(row) + ",\n")
    f.write("};\n")
    f.write(f"static const int {name}_W = {w}, {name}_H = {h};\n\n")


def main():
    im1 = Image.open(os.path.join(ASSETS, "logo@1x.png")).convert("RGBA")
    im16 = Image.open(os.path.join(ASSETS, "logo@1.6x.png")).convert("RGBA")
    x0, x1 = banana_columns(im1)
    y0 = 0
    y1 = im1.size[1]
    im1 = im1.crop((x0, y0, x1, y1))
    # the 1.6x logo is 1.6x the 1x: the same crop in its own pixels
    a0, a1 = banana_columns(im16)
    im16 = im16.crop((a0, 0, a1, im16.size[1]))
    out = os.path.join(APP, "activity-logo.h")
    with open(out, "w", encoding="ascii") as f:
        f.write("// The menu's banana, cropped from ui/assets/rnds/logo@1x.png and logo@1.6x.png.\n")
        f.write("// Generated by tools/make-logo.py - do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        emit(f, "AF_LOGO_1X", im1)
        emit(f, "AF_LOGO_16", im16)
    print("wrote", out, im1.size, im16.size)


if __name__ == "__main__":
    main()
