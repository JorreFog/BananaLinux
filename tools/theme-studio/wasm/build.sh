#!/bin/sh
# Banana Theme Studio: builds the engine for the browser (wasm/banana-engine.js) with Emscripten.
#
#   sh tools/theme-studio/wasm/build.sh          # needs em++ on PATH (source ~/emsdk/emsdk_env.sh), ImageMagick
#
# One .js file with the wasm and its data inlined (-sSINGLE_FILE), so index.html can load it with a plain <script>
# tag from file:// (a page opened from disk can't fetch() a .wasm beside it). Embedded: the built-in fonts and
# icons (ui/assets/rnds, ui/assets/banana/fonts), systems.conf and ui/tests/fixture.sh's made-up library.
# The sources' hash is written into the output (BananaEngineBuild.sources); tests/run.sh says when it is stale.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
UI=$ROOT/ui
OUT=$HERE/banana-engine.js
command -v em++ >/dev/null 2>&1 || { echo "em++ isn't on PATH (install emsdk, then: source <emsdk>/emsdk_env.sh)" >&2; exit 1; }

STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT

# the made-up library, as serve.py's previews use it; Yellow Planet's zipped ROM is made small (fixture.sh pads it to
# 3 MB of noise to test reading deep into a zip, which a web page needn't carry)
sh "$UI/tests/fixture.sh" "$STAGE/fx" >/dev/null
python3 - "$STAGE/fx/roms/nds/Yellow Planet [!].zip" <<'PY'
import struct, sys, zipfile
at = 0x1000
rom = bytearray(at + 0x840)
rom[0x68:0x6c] = struct.pack('<I', at)
b = bytearray(0x840)
b[0:2] = struct.pack('<H', 1)
for t in range(16):
    for y in range(8):
        for x in range(0, 8, 2):
            px = [((t % 4) * 8 + x + i - 15.5) ** 2 + ((t // 4) * 8 + y - 15.5) ** 2 < 14 ** 2 for i in (0, 1)]
            b[0x20 + t * 32 + y * 4 + x // 2] = (1 if px[0] else 0) | ((1 if px[1] else 0) << 4)
b[0x222:0x224] = struct.pack('<H', 31 | (28 << 5) | (4 << 10))
rom[at:at + 0x840] = b
with zipfile.ZipFile(sys.argv[1], 'w', zipfile.ZIP_DEFLATED) as z:
    z.writestr('readme.txt', 'not the game')
    z.writestr('Yellow Planet (Europe).nds', bytes(rom))
PY
cp "$ROOT/system/rootfs/etc/banana/systems.conf" "$STAGE/fx/systems.conf"
# the same with a game for every system systems.conf lists (to see each one's icon): a made-up ROM in each folder,
# and the apps' entries in /fxall/apps, its own systems.conf pointing the apps there (the /fx library has no apps,
# as a computer's /usr/share/banana/apps is empty)
cp -r "$STAGE/fx" "$STAGE/fxall"
python3 - "$STAGE/fxall/systems.conf" "$STAGE/fxall/roms" "$STAGE/fxall/apps" <<'PY'
import os, re, sys, unicodedata
conf, roms, apps = sys.argv[1:4]
cur, secs = None, []
for ln in open(conf, encoding="utf-8"):
    ln = ln.strip()
    if ln.startswith("[") and ln.endswith("]"):
        cur = {"id": ln[1:-1]}; secs.append(cur)
    elif cur is not None and "=" in ln and not ln.startswith("#"):
        k, v = ln.split("=", 1); cur[k.strip()] = v.strip()
for s in secs:
    folder, exts = s.get("folder", s["id"]), s.get("ext", "").split()
    if not exts:
        continue
    if folder.startswith("/usr/share/banana/apps/"):
        d = os.path.join(apps, folder[len("/usr/share/banana/apps/"):])
    elif folder.startswith("/"):
        continue
    else:
        d = os.path.join(roms, folder)
    os.makedirs(d, exist_ok=True)
    if not any(f.lower().endswith("." + exts[0].lower()) for f in os.listdir(d)):
        name = unicodedata.normalize("NFKD", s.get("name", s["id"])).encode("ascii", "ignore").decode()	# (the packager wants ASCII)
        open(os.path.join(d, name + "." + exts[0]), "wb").write(b"\0" * 1024)
text = open(conf, encoding="utf-8").read()
open(conf, "w", encoding="utf-8").write(re.sub(r"(?m)^folder = /usr/share/banana/apps/", "folder = /fxall/apps/", text))
PY
mkdir -p "$STAGE/rnds" "$STAGE/banana/fonts"
(cd "$UI/assets/rnds" && cp -r fonts icons systems.cfg ./*.png "$STAGE/rnds/")
cp "$UI"/assets/banana/fonts/*.ttf "$STAGE/banana/fonts/"
cp "$UI"/assets/banana/*.png "$STAGE/banana/"

SRC="src/layout.cpp src/expr.cpp src/json.cpp src/library.cpp src/theme.cpp src/soft.cpp src/zip.cpp rnds/RndsRaster.cpp rnds/RndsUI.cpp"
HASH=$(sh "$HERE/sources.sh")
STAMP=$(date -u +%Y-%m-%dT%H:%MZ)
COMMIT=$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)

cd "$UI"
em++ -O2 -std=c++17 -Wno-unused-function -sUSE_FREETYPE=1 -sUSE_ZLIB=1 \
    -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=64MB -sSINGLE_FILE=1 -sMODULARIZE=1 -sEXPORT_NAME=BananaEngineModule \
    -sENVIRONMENT=web,node -sFILESYSTEM=1 -sEXIT_RUNTIME=0 \
    -sEXPORTED_RUNTIME_METHODS='["cwrap","ccall","FS","HEAPU8","HEAPU32"]' \
    --embed-file "$STAGE/fx@/fx" --embed-file "$STAGE/rnds@/rnds" --embed-file "$STAGE/banana@/banana" \
    --embed-file "$STAGE/fxall@/fxall" \
    $SRC "$HERE/theme-wasm.cpp" -o "$STAGE/engine.js"
{
    echo "// Banana Theme Studio: banana-ui's theme engine for the browser. GENERATED by wasm/build.sh, do not edit."
    echo "// built $STAMP from $COMMIT; sources $HASH"
    echo "var BananaEngineBuild = { built: \"$STAMP\", commit: \"$COMMIT\", sources: \"$HASH\" };"
    cat "$STAGE/engine.js"
} >"$OUT"
echo "wrote $OUT ($(du -h "$OUT" | cut -f1), sources $HASH)"
